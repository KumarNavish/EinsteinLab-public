import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const out=path.resolve('../evidence/runtime/c2');
const report={scope:'Actual localhost browser, real GLB/animations and local inference/TTS. No mocked service. Desktop only.',checks:[],errors:[],warnings:[],httpErrors:[]};
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:path.join(out,'videos'),size:{width:1440,height:1000}}});
const page=await context.newPage();
page.on('pageerror',e=>report.errors.push(e.message));page.on('console',m=>{if(m.type()==='error')report.errors.push(m.text());if(m.type()==='warning')report.warnings.push(m.text());});page.on('response',r=>{if(r.status()>=400)report.httpErrors.push({url:r.url(),status:r.status()});});
const check=(name,passed,extra={})=>report.checks.push({name,passed,...extra});
try{
 for(let attempt=0;attempt<40;attempt++){try{const r=await context.request.get('http://127.0.0.1:8765/api/health');if(r.ok()){report.health=await r.json();break;}}catch{}await new Promise(r=>setTimeout(r,1500));}
 if(!report.health)throw new Error('Runtime did not become ready');
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle',timeout:90000});
 await page.waitForFunction(()=>window.__einstein?.stats.avatarReady,{},{timeout:90000});
 await page.waitForTimeout(1400);
 check('identity',(await page.title())==='Einstein · Mobiliar Lab');
 report.idle=await page.evaluate(()=>window.__einstein.stats);
 check('original_motion_loaded',report.idle.motion?.tracks>100,report.idle.motion||{});
 await page.screenshot({path:path.join(out,'desktop-idle.png'),fullPage:false});
 await page.locator('#evidence-only').uncheck();
 await page.locator('#voice-mode').selectOption('expressive');
 await page.locator('#question').fill('What does the GenAI in VR project investigate?');await page.locator('#send').click();
 await page.waitForFunction(()=>window.__einstein.stats.lastTurn?.question==='What does the GenAI in VR project investigate?',{},{timeout:60000});
 await page.waitForFunction(()=>window.__einstein.stats.audioPlaying,{},{timeout:60000});
 await page.waitForTimeout(600);
 const before=await page.evaluate(()=>{const s=window.__einstein.stage;const b=s.model.getObjectByName('CC_Base_L_Hand');return b?b.getWorldPosition(s.camera.position.clone()).toArray():null;});
 await page.waitForTimeout(1200);
 const after=await page.evaluate(()=>{const s=window.__einstein.stage;const b=s.model.getObjectByName('CC_Base_L_Hand');return b?b.getWorldPosition(s.camera.position.clone()).toArray():null;});
 report.speaking=await page.evaluate(()=>window.__einstein.stats);
 check('grounded_generated_answer',report.speaking.lastTurn.sources.some(u=>u.includes('genai-in-vr')));
 check('phoneme_timing_present',report.speaking.mouthCueCount>10);
 check('original_gesture_moves',before&&after&&Math.hypot(...before.map((v,i)=>v-after[i]))>.002,{before,after});
 await page.screenshot({path:path.join(out,'desktop-speaking.png'),fullPage:false});
 await page.locator('#source-toggle').click();
 await page.screenshot({path:path.join(out,'desktop-evidence.png'),fullPage:false});
 const began=performance.now();await page.locator('#interrupt').click();
 await page.waitForFunction(()=>!window.__einstein.stats.audioPlaying&&window.__einstein.stats.state==='ready');
 check('interrupt_stops_playback',true,{button_to_ready_ms:Math.round(performance.now()-began)});
 await page.waitForTimeout(450);
 check('mouth_returns_to_rest',await page.evaluate(()=>window.__einstein.stage.current.jaw<.01));
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(700);
 check('mobile_no_horizontal_overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.screenshot({path:path.join(out,'mobile-conversation.png'),fullPage:true});
 report.final=await page.evaluate(()=>window.__einstein.stats);
 check('console_clean',report.errors.length===0&&report.httpErrors.length===0);
}catch(error){report.failure=error.stack;await page.screenshot({path:path.join(out,'browser-failure.png')}).catch(()=>{});}
const video=page.video();await context.close();report.video=await video.path();await browser.close();
await fs.writeFile(path.join(out,'browser-qa.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
if(report.failure||report.checks.some(c=>!c.passed))process.exitCode=1;
