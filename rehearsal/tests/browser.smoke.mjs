import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve('..'), evidence=path.join(root,'evidence/runtime');
const errors=[],warnings=[];
const report={scope:'Isolated automated desktop test; no real-user browser state touched. Ego open receipt remains uncertain and was not replayed.',checks:[],input:'Typed questions and, when available, a clearly synthetic local audio fixture. Not a physical Quest or human microphone test.'};
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1440,height:960},recordVideo:{dir:path.join(evidence,'videos'),size:{width:1280,height:854}}});
const page=await context.newPage();
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());if(m.type()==='warning')warnings.push(m.text());});
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle',timeout:90000});
 await page.waitForFunction(()=>window.__einstein?.stats.avatarReady,{},{timeout:90000});
 await page.waitForTimeout(1800);
 report.checks.push({name:'page_identity',passed:(await page.title())==='Einstein · Mobiliar Lab',url:page.url()});
 report.checks.push({name:'real_avatar_loaded',passed:await page.evaluate(()=>window.__einstein.stats.avatarReady)});
 await page.screenshot({path:path.join(evidence,'desktop-idle.png'),fullPage:false});
 await page.locator('#evidence-only').check();
 await page.locator('#question').fill('How do LLMs affect cognitive load?');
 await page.locator('#send').click();
 await page.waitForFunction(()=>window.__einstein.stats.lastTurn?.question==='How do LLMs affect cognitive load?',{},{timeout:45000});
 await page.waitForFunction(()=>window.__einstein.stats.audioPlaying,{},{timeout:10000});
 report.turn=await page.evaluate(()=>window.__einstein.stats.lastTurn);
 report.checks.push({name:'grounded_question_response',passed:report.turn.sources.some(s=>s.includes('llms-and-cognitive-load'))});
 report.checks.push({name:'real_audio_playing',passed:await page.evaluate(()=>window.__einstein.stats.audioPlaying)});
 await page.locator('#source-toggle').click();
 await page.screenshot({path:path.join(evidence,'desktop-conversation.png'),fullPage:false});
 const started=Date.now();await page.locator('#interrupt').click();
 await page.waitForFunction(()=>!window.__einstein.stats.audioPlaying&&window.__einstein.stats.state==='ready');
 report.checks.push({name:'playback_interrupt',passed:true,observed_button_to_ready_ms:Date.now()-started});
 report.render=await page.evaluate(()=>window.__einstein.stats.frame);
 report.webgl=await page.evaluate(()=>{const c=document.querySelector('canvas');const gl=c.getContext('webgl2');if(!gl)return null;const e=gl.getExtension('WEBGL_debug_renderer_info');return {renderer:e?gl.getParameter(e.UNMASKED_RENDERER_WEBGL):gl.getParameter(gl.RENDERER),version:gl.getParameter(gl.VERSION)};});
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(700);
 report.checks.push({name:'mobile_no_horizontal_overflow',passed:await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)});
 await page.screenshot({path:path.join(evidence,'mobile-conversation.png'),fullPage:true});
 report.checks.push({name:'no_javascript_errors',passed:errors.length===0});
}catch(e){report.failure=e.stack;await page.screenshot({path:path.join(evidence,'ui-failure.png'),fullPage:false}).catch(()=>{});}
report.errors=errors;report.warnings=warnings;
const video=page.video();await context.close();report.video=await video.path();await browser.close();
await fs.writeFile(path.join(evidence,'browser-smoke.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
if(report.failure||report.checks.some(c=>!c.passed))process.exitCode=1;
