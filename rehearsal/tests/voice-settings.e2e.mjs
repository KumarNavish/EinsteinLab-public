import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const out = path.resolve('../evidence/runtime/c7/settings-' + Date.now());
await fs.mkdir(out, {recursive: true});
const report = {scope: 'Actual renderer and recorded native-voice samples. No new provider generation, real microphone, or credential modification.', checks: [], errors: [], providerPosts: []};
const browser = await chromium.launch({channel: 'chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required']});
const context = await browser.newContext({viewport: {width: 1440, height: 1000}});
const page = await context.newPage();
page.on('pageerror', error => report.errors.push(error.message));
page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/api/native/')) report.providerPosts.push(request.url().split('?')[0]); });
const check = (name, passed) => report.checks.push({name, passed: Boolean(passed)});
try {
  await page.goto('http://127.0.0.1:8765/', {waitUntil: 'networkidle', timeout: 60000});
  await page.waitForFunction(() => window.__einstein?.stats.avatarReady && window.__einstein.stats.voicePreferencesLoaded, {}, {timeout: 60000});
  await page.screenshot({path: path.join(out, 'idle-materials.png')});
  await page.locator('#portrait').click(); await page.waitForTimeout(500);
  await page.screenshot({path: path.join(out, 'portrait-materials.png')});
  await page.getByRole('button', {name: 'Conversation settings', exact: true}).click();
  check('native_voice_exposed_not_local_voice', await page.locator('#native-voice').isVisible() && !(await page.locator('#voice-mode').isVisible()));
  await page.locator('#native-voice').selectOption('Algenib');
  await page.locator('#preview-voice').click();
  await page.waitForFunction(() => window.__einstein.stats.audioPlaying, {}, {timeout: 12000});
  check('recorded_sample_actually_plays', true);
  await page.locator('#sound').uncheck(); await page.waitForTimeout(200);
  check('mute_controls_native_audio_graph', await page.evaluate(() => window.__einstein.player.master.gain.value < .001));
  await page.locator('#sound').check();
  await page.waitForFunction(() => !window.__einstein.stats.audioPlaying && window.__einstein.player.entries.length === 0, {}, {timeout: 12000});
  check('preview_does_not_open_microphone', await page.evaluate(() => !window.__einstein.stats.microphoneActive));
  check('preview_makes_zero_provider_requests', report.providerPosts.length === 0);
  check('audio_face_loaded_in_actual_browser', await page.evaluate(() => window.__einstein.stats.audioFaceReady));
  await page.screenshot({path: path.join(out, 'settings-with-real-voices.png')});
  await page.reload({waitUntil: 'networkidle'});
  await page.waitForFunction(() => window.__einstein?.stats.voicePreferencesLoaded);
  check('native_selection_survives_reload', await page.locator('#conversation-engine').inputValue() === 'native');
  check('actual_voice_survives_reload', await page.locator('#native-voice').inputValue() === 'Algenib');
  await page.getByRole('button', {name: 'Conversation settings', exact: true}).click();
  await page.locator('#conversation-engine').selectOption('local'); await page.waitForTimeout(150);
  check('local_mode_reveals_only_local_controls', await page.locator('#voice-mode').isVisible() && !(await page.locator('#native-voice').isVisible()));
  await page.locator('#conversation-engine').selectOption('native'); await page.waitForTimeout(150);
  await page.setViewportSize({width: 390, height: 844}); await page.waitForTimeout(300);
  await page.screenshot({path: path.join(out, 'mobile-settings.png')});
  check('mobile_controls_fit', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  check('no_javascript_errors', report.errors.length === 0);
} catch (failure) { report.failure = failure.stack; await page.screenshot({path: path.join(out, 'failure.png')}).catch(() => {}); }
await browser.close();
await fs.writeFile(path.join(out, 'report.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify({directory: out, ...report}, null, 2));
if (report.failure || report.checks.some(item => !item.passed)) process.exitCode = 1;
